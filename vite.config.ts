import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Plugin } from 'vite';
import { defineConfig } from 'vitest/config';

const projectDir = fileURLToPath(new URL('.', import.meta.url));

/** Escape sequences that would end or confuse an inline <script> element. */
function inlineSafe(code: string): string {
  return code.replace(/<\/script/gi, '\\x3C/script').replace(/<script/gi, '\\x3Cscript').replace(/<!--/g, '\\x3C!--');
}

/**
 * Inline the bundled JS and CSS into index.html and drop the separate files,
 * so the app is one file that also works when opened from disk (file://),
 * where browsers refuse to load external module scripts. The result is copied
 * to the project root as the ready-to-open index.html.
 */
function singleFileApp(): Plugin {
  return {
    name: 'pvz-single-file-app',
    apply: 'build',
    enforce: 'post',
    generateBundle(_options, bundle) {
      const page = bundle['index.html'];
      if (!page || page.type !== 'asset') return;
      let html = String(page.source);
      for (const [fileName, item] of Object.entries(bundle)) {
        if (item.type === 'chunk') {
          const tag = new RegExp(`\\s*<script[^>]*\\ssrc="[^"]*${fileName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"[^>]*></script>`);
          if (!tag.test(html)) this.error(`Could not find the <script> tag for ${fileName}`);
          html = html.replace(tag, '');
          // A classic script at the end of <body> runs after the DOM is parsed, like a module would.
          html = html.replace('</body>', () => `<script>${inlineSafe(item.code)}</script>\n  </body>`);
          delete bundle[fileName];
        } else if (fileName.endsWith('.css')) {
          const tag = new RegExp(`<link[^>]*\\shref="[^"]*${fileName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"[^>]*>`);
          if (!tag.test(html)) this.error(`Could not find the stylesheet link for ${fileName}`);
          html = html.replace(tag, () => `<style>${String(item.source).replace(/<\/style/gi, '<\\/style')}</style>`);
          delete bundle[fileName];
        }
      }
      const leftovers = Object.keys(bundle).filter((f) => f !== 'index.html');
      if (leftovers.length) this.error(`Files were not inlined into index.html: ${leftovers.join(', ')}`);
      const note = '<!-- Generated by "npm run build" from src/ - edit the sources there, not this file. -->';
      page.source = html.replace(/^(\s*<!doctype html>)/i, (doctype) => `${doctype}\n${note}`);
    },
    // Runs only after a successful write, so a failed build never replaces the root page.
    writeBundle(_options, bundle) {
      const page = bundle['index.html'];
      if (page?.type === 'asset') writeFileSync(path.join(projectDir, 'index.html'), page.source);
    },
  };
}

export default defineConfig({
  root: 'src',
  base: './',
  publicDir: false,
  plugins: [singleFileApp()],
  build: {
    outDir: '../dist',
    emptyOutDir: true,
    target: 'es2022',
    sourcemap: false,
    cssCodeSplit: false,
    modulePreload: false,
    assetsInlineLimit: Number.MAX_SAFE_INTEGER,
    rollupOptions: {
      output: { format: 'iife', inlineDynamicImports: true },
    },
  },
  test: {
    root: projectDir,
    include: ['tests/**/*.test.ts'],
    environment: 'node',
  },
});
